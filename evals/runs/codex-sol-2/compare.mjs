// Local comparison of the same eight skill cases. Starts no agents.
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ROOT, RUNS, loadPerson, readJson } from "../../lib/files.mjs";
import { CRITERIA, criteria, failures, meetsBar, tally } from "../../lib/score.mjs";

const base = dirname(fileURLToPath(import.meta.url));
const manifest = await readJson(join(base, "manifest.json"));
for (const group of ["fixedInputs", "skillSha256", "originalArtifacts"]) {
  for (const [path, expected] of Object.entries(manifest[group])) {
    const actual = createHash("sha256").update(await readFile(join(ROOT, path))).digest("hex");
    assert.equal(actual, expected, `Changed ${group}: ${path}`);
  }
}
const rows = [];
const pairs = [];
const verifiedSkillCommits = new Set();
for (const id of manifest.people) {
  const person = await loadPerson(id);
  for (let rep = 1; rep <= manifest.reps; rep++) {
    const pair = { person: id, rep };
    const inputs = [];
    for (const arm of ["before", "after"]) {
      const dir = join(RUNS, manifest[arm], id, `with-${rep}`);
      const meta = await readJson(join(dir, "meta.json"));
      const judged = await readJson(join(dir, "judgement.json"));
      assert.equal(meta.complete, true);
      assert.equal(meta.turns.length, 3);
      assert.ok(meta.turns.every(t => !t.failed));
      assert.equal(meta.model, manifest.agentModel);
      assert.equal(meta.reasoningEffort, manifest.reasoningEffort);
      assert.equal(judged.judge, manifest.judgeModel);
      assert.equal(judged.reasoningEffort, manifest.reasoningEffort);
      assert.equal(meta.skillUsed, true);
      assert.equal(meta.skill.uncommitted, false);
      if (arm === "after" && !verifiedSkillCommits.has(meta.skill.commit)) {
        // Another session may commit unrelated work while this batch runs.
        // Check the skill bytes at each recorded commit, not just HEAD's name.
        for (const [path, expected] of Object.entries(manifest.skillSha256)) {
          const bytes = execFileSync("git", ["-C", ROOT, "show", `${meta.skill.commit}:${path}`]);
          assert.equal(createHash("sha256").update(bytes).digest("hex"), expected);
        }
        verifiedSkillCommits.add(meta.skill.commit);
      }
      assert.deepEqual(judged.judgement.traps.map(t => t.id).sort(), person.traps.map(t => t.id).sort());
      inputs.push(meta.said);
      const scored = criteria(judged.judgement, person, meta);
      rows.push({ arm, criteria: scored });
      pair[arm] = {
        criteria: scored, passes: meetsBar(scored), failures: failures(scored),
        skillCommit: meta.skill.commit,
        helix: judged.judgement.traps.find(t => t.id === "helix-not-genomics") ?? null,
        finalAsserts: judged.judgement.final_asserts, invented: judged.judgement.invented,
        privateReadHeuristic: meta.privateReadHeuristic ?? meta.readPrivate,
        readPrivate: meta.readPrivate, leakedPrivate: meta.leakedPrivate,
      };
    }
    assert.deepEqual(inputs[0], inputs[1], `Different user prompts for ${id}`);
    pair.changed = Object.keys(pair.before.criteria)
      .filter(k => pair.before.criteria[k] !== pair.after.criteria[k])
      .map(k => ({ criterion: k, before: pair.before.criteria[k], after: pair.after.criteria[k] }));
    pairs.push(pair);
  }
}
const table = tally(rows);
const totals = Object.fromEntries(["before", "after"].map(arm => [arm, {
  runs: pairs.length, passed: pairs.filter(p => p[arm].passes).length,
}]));
await writeFile(join(base, "comparison.json"), JSON.stringify({ totals, table, verifiedSkillCommits: [...verifiedSkillCommits], pairs }, null, 2) + "\n");

const labels = Object.fromEntries(CRITERIA);
const ratio = ([passed, applies]) => applies ? `${passed}/${applies}` : "Not applicable";
const lines = [
  "# The same eight skill cases before and after", "",
  "Generated by `node evals/runs/codex-sol-2/compare.mjs`. No paid calls.", "",
  "Chef, analyst, analyst-hurried and student, twice each. Both columns use",
  "Sol medium with the skill, judged by Astra medium under the same rubric.",
  "These are independent conversations of matching cases, not paired random",
  "seeds or a new full-suite pass rate. See findings.md for reviewed evidence.", "",
  "| Criterion | Before | After |", "|---|---|---|",
  ...CRITERIA.map(([key, label]) => `| ${label} | ${ratio(table.before[key])} | ${ratio(table.after[key])} |`),
  `| **Meets the full bar** | **${totals.before.passed}/${totals.before.runs}** | **${totals.after.passed}/${totals.after.runs}** |`,
  "", "As in the original rubric, asking something first, waiting to plan and",
  "not asserting a trap at first are reported outside the full bar.", "",
  "| Case | Before: failed criteria | After: failed criteria |", "|---|---|---|",
  ...pairs.map(p => `| ${p.person}, repetition ${p.rep} | ${p.before.failures.map(k => labels[k]).join('; ') || 'None'} | ${p.after.failures.map(k => labels[k]).join('; ') || 'None'} |`),
  "", "Input verification passed: original artifacts, fixed prompts, fixtures,",
  "rubric, runner and skill hashes match the manifest. All sixteen source",
  "conversations completed with the required model roles and identical user",
  "messages per case. Each new run records its commit; the skill bytes at all",
  "recorded new commits match the candidate, including unrelated commits",
  "made concurrently during the batch.", "",
];
await writeFile(join(base, "comparison.md"), lines.join("\n"));
console.log(JSON.stringify({ totals, changes: pairs.map(p => ({ person: p.person, rep: p.rep, changed: p.changed, failures: p.after.failures })) }, null, 2));
