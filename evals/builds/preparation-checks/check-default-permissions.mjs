import { spawn } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildCodexArgs } from "../../lib/build.mjs";
const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const capabilities = JSON.parse(await readFile(join(root, "evals/builds/local-capabilities.json"), "utf8"));
const all = buildCodexArgs(capabilities);
const config = [];
for (let index = 0; index < all.length; index++) if (all[index] === "-c") config.push("-c", all[++index]);
const command = ["sandbox", ...config, "--", process.execPath, join(here, "default-permissions-child.mjs")];
const report = { modelCalls: 0, date: "2026-10-11", executable: "codex", cwd: root, command, selection: "default_permissions from the exact actor config; no -P, no -C", limitations: "The standalone sandbox command has no --ignore-user-config option; this tests its default selector with current user config. Actor exec uses --ignore-user-config." };
const child = spawn("codex", command, { cwd: root, stdio: ["ignore", "pipe", "pipe"] });
let stdout = "", stderr = "";
const timer = setTimeout(() => child.kill("SIGKILL"), 20000);
child.stdout.on("data", chunk => { stdout += chunk; });
child.stderr.on("data", chunk => { stderr += chunk; });
child.on("error", error => { report.error = String(error); });
await new Promise(done => child.once("close", (code, signal) => { clearTimeout(timer); Object.assign(report, { code, signal, stdout, stderr }); done(); }));
await writeFile(join(here, "default-permissions-proof.json"), JSON.stringify(report, null, 2) + "\n", { flag: "wx" });
console.log(JSON.stringify(report, null, 2));
process.exitCode = report.code === 0 ? 0 : 1;
